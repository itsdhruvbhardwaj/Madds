    val backgrounds = listOf("gold", "ivory", "clay", "sage", "slate", "charcoal")
    val defaultAvatar get() = avatars.first()
    val defaultBackground get() = backgrounds.first()
    fun initialSelection(user: User): AvatarSelectionDefaults {
        val firstSetup = user.profileSetupComplete == false
        val photo = !firstSetup && (user.profileAppearance ?: "photo") == "photo" && user.profileImage?.startsWith("https://") == true
        return AvatarSelectionDefaults(
            avatarId = if (firstSetup) defaultAvatar.id else find(user.avatarId)?.id ?: defaultAvatar.id,
            background = if (!firstSetup && user.profileAppearance == "avatar") user.avatarBackground?.takeIf { it in backgrounds } ?: defaultBackground else defaultBackground,
            mode = if (photo) "photo" else "avatar",
            tab = if (photo) 1 else 0
        )
    }
    fun find(id: String?) = avatars.find { it.id == id }
